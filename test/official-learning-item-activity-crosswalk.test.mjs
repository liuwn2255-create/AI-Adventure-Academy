import test from 'node:test';
import assert from 'node:assert/strict';
import { buildOfficialLearningItemCrosswalk, validateOfficialLearningItemCrosswalk } from '../scripts/official-learning-item-activity-crosswalk.mjs';
import { GRADE_CATALOG } from '../prototype/data/gradeCatalog.js';
import { getGradeAdventureSummary } from '../prototype/data/gradeActivityDirectory.js';

test('official item crosswalk preserves the bounded 131-row math inventory and real activity evidence', () => {
  const report = buildOfficialLearningItemCrosswalk();
  const validation = validateOfficialLearningItemCrosswalk(report);
  assert.deepEqual(validation.errors, []);
  assert.equal(report.status, 'partial_inventory_not_complete_official_elementary_curriculum');
  assert.equal(report.mathOfficialLearningContentItems.length, 131);
  assert.equal(report.scope.mathUniqueOfficialContentCodes, 131);
  assert.deepEqual(report.mathCoverageCountsWithinRegisteredRows, { partial: 79, relation_only: 8, uncovered: 44, needs_verification: 0 });
  assert.equal(report.scope.mathOfficialLearningPerformanceRows, 58);
  assert.equal(report.scope.officialDocumentFamilyCount, 15);
  assert.equal(report.scope.fullyEnumeratedOfficialDocumentFamilyCount, 0);
  assert.equal(report.scope.officialElementaryItemTotal, null);
  assert.equal(report.scope.nationalCoverageRate, null);
  assert.equal(report.registeredProjectFocusCrosswalk.length, report.scope.registeredProjectFocusRows);
  const catalogActivityIds = GRADE_CATALOG.flatMap((grade) => getGradeAdventureSummary(grade).subjects.flatMap((subject) => subject.activities.map(({ activityId }) => activityId))).sort();
  assert.deepEqual(report.actualRegisteredActivities.map(({ activityId }) => activityId).sort(), catalogActivityIds);
  assert.ok(report.mathOfficialLearningContentItems.find(({ officialCode }) => officialCode === 'N-2-4').activityIds.includes('ACT-G2-MATH-LIFE-ESTIMATION-HUNDREDS-CANDIDATE'));
  assert.ok(report.mathOfficialLearningContentItems.find(({ officialCode }) => officialCode === 'N-2-11').activityIds.includes('ACT-G2-MATH-LENGTH-MEASURE-CONVERT-CANDIDATE'));
  const moneyItem = report.mathOfficialLearningContentItems.find(({ officialCode }) => officialCode === 'N-2-5');
  assert.ok(moneyItem.activityIds.includes('ACT-G2-MATH-MONEY-COMBINATION-MARKET-CANDIDATE'));
  assert.equal(moneyItem.coverageStatus, 'partial');
  const inbSlice = report.verifiedNonMathOfficialContentSlices.find(({ batchId }) => batchId === 'natural-science-stage2-inb-content-slice-pdf-page-20');
  assert.equal(inbSlice?.officialContentRowCount, 7);
  assert.equal(inbSlice?.items.find(({ officialCode }) => officialCode === 'INb-II-2')?.activityEvidenceStatus, 'partial');
  assert.equal(inbSlice?.items[0].printedPage, 16, 'footer image establishes PDF sequence 20 as printed page 16');
  assert.equal(inbSlice?.items.filter(({ activityEvidenceStatus }) => activityEvidenceStatus === 'uncovered').length, 3);
  const scienceSlice = report.verifiedNonMathOfficialContentSlices.find(({ batchId }) => batchId === 'natural-science-stage2-ina-content-slice-pdf-page-19');
  assert.equal(scienceSlice?.officialContentRowCount, 8);
  assert.equal(scienceSlice?.items[0].printedPage, 15, 'footer image establishes PDF sequence 19 as printed page 15');
  assert.equal(scienceSlice?.items.find(({ officialCode }) => officialCode === 'INa-II-3')?.activityEvidenceStatus, 'partial');
  assert.equal(scienceSlice?.items.filter(({ activityEvidenceStatus }) => activityEvidenceStatus === 'uncovered').length, 7);
  const inc = report.verifiedNonMathOfficialContentSlices.find(({ batchId }) => batchId === 'natural-science-stage2-inc-content-slice-pdf-pages-20-21');
  assert.equal(inc?.officialContentRowCount, 10);
  assert.equal(inc?.items[0].printedPage, 16);
  assert.deepEqual(inc?.items.map(({ officialCode }) => officialCode), Array.from({ length: 10 }, (_, index) => `INc-Ⅱ-${index + 1}`));
  assert.equal(inc?.items.filter(({ activityEvidenceStatus }) => activityEvidenceStatus === 'relation_only').length, 4);
  assert.equal(inc?.items.filter(({ activityEvidenceStatus }) => activityEvidenceStatus === 'uncovered').length, 6);
  const ind = report.verifiedNonMathOfficialContentSlices.find(({ batchId }) => batchId === 'natural-science-stage2-ind-content-slice-pdf-pages-21-22');
  assert.equal(ind?.officialContentRowCount, 9);
  assert.deepEqual(ind?.items.map(({ officialCode }) => officialCode), Array.from({ length: 9 }, (_, index) => `INd-Ⅱ-${index + 1}`));
  assert.equal(ind?.items.filter(({ activityEvidenceStatus }) => activityEvidenceStatus === 'partial').length, 2);
  assert.equal(ind?.items.filter(({ activityEvidenceStatus }) => activityEvidenceStatus === 'relation_only').length, 4);
  assert.equal(ind?.items.filter(({ activityEvidenceStatus }) => activityEvidenceStatus === 'uncovered').length, 3);
  const ine = report.verifiedNonMathOfficialContentSlices.find(({ batchId }) => batchId === 'natural-science-stage2-ine-content-slice-pdf-pages-23-24');
  assert.equal(ine?.officialContentRowCount, 11);
  assert.equal(ine?.items.at(-1).officialText, '環境的變化會影響植物生長。');
  assert.equal(ine?.items.at(-1).pdfPageSequence, 24, 'INe-II-11 continuation ends at page sequence 24');
  assert.equal(ine?.items.filter(({ activityEvidenceStatus }) => activityEvidenceStatus === 'relation_only').length, 7);
  assert.equal(ine?.items.filter(({ activityEvidenceStatus }) => activityEvidenceStatus === 'uncovered').length, 3);
  const socialSlice = report.verifiedNonMathOfficialContentSlices.find(({ batchId }) => batchId === 'social-studies-stage2-ba-a-individual-difference-pdf-page-100');
  assert.equal(socialSlice?.officialContentRowCount, 1);
  assert.equal(socialSlice?.items[0].officialCode, 'Ba-Ⅱ-1');
  assert.equal(socialSlice?.items[0].activityEvidenceStatus, 'partial');
  assert.ok(socialSlice?.items[0].activityEvidence[0].interactionStages.some(({ stageId }) => stageId === 'compare-shared-and-different-viewpoints'));
  assert.equal(report.verifiedNonMathBoundedSliceCounts.registeredOfficialContentRows, 57);
  assert.deepEqual(report.verifiedNonMathBoundedSliceCounts.byCoverageStatus, { partial: 8, relation_only: 20, uncovered: 29, needs_verification: 0 });
  assert.ok(report.actualRegisteredActivities.every((activity) => ['directory_launch_and_return_verified', 'not_verified'].includes(activity.browserEntryVerification.status)));
  const grade2Classification = report.actualRegisteredActivities.find(({ activityId }) => activityId === 'ACT-G2-MATH-DATA-CLASSIFICATION-NESTED-GROUPS-CANDIDATE');
  assert.equal(grade2Classification?.browserEntryVerification.status, 'directory_launch_and_return_verified');
  assert.equal(grade2Classification?.browserEntryVerification.returnedToCorrectDirectory, true);
  assert.match(grade2Classification?.browserEntryVerification.reportPath ?? '', /artifacts\/learning-subitems-browser-acceptance\/runs\/g2-data-classification-\d+\.json/u);
  assert.match(grade2Classification?.browserEntryVerification.executedAt ?? '', /^2026-10-25T13:1\d:/u);
  for (const activityId of ['ACT-G2-MATH-UNKNOWN-QUANTITY-MODEL-CANDIDATE', 'ACT-G2-MATH-UNIT-FRACTION-PAPER-FOLD-MODEL-CANDIDATE']) {
    const activity = report.actualRegisteredActivities.find((entry) => entry.activityId === activityId);
    assert.equal(activity?.browserEntryVerification.status, 'directory_launch_and_return_verified');
    assert.equal(activity?.browserEntryVerification.returnedToCorrectDirectory, true);
    assert.match(activity?.browserEntryVerification.reportPath ?? '', /g2-math-workshops-\d+\.json/u);
  }
  const moneyActivity = report.actualRegisteredActivities.find(({ activityId }) => activityId === 'ACT-G2-MATH-MONEY-COMBINATION-MARKET-CANDIDATE');
  assert.equal(moneyActivity?.browserEntryVerification.status, 'directory_launch_and_return_verified');
  assert.equal(moneyActivity?.browserEntryVerification.returnedToCorrectDirectory, true);
  assert.match(moneyActivity?.browserEntryVerification.reportPath ?? '', /learning-subitems-browser-acceptance\/runs\/g2-money-market-\d+\.json/u);
  assert.ok(report.mathOfficialLearningContentItems.every((item) => item.officialText && item.source.sourceLocation && item.relatedPerformanceCodes.length));
  assert.ok(report.mathOfficialLearningContentItems.every((item) => ['partial', 'relation_only', 'uncovered', 'needs_verification'].includes(item.coverageStatus)));
});

test('crosswalk rejects invalid activity references and does not promote code-only links to interactive coverage', () => {
  const report = buildOfficialLearningItemCrosswalk();
  const anyMathItem = report.mathOfficialLearningContentItems[0];
  anyMathItem.activityIds = ['UNKNOWN-ACTIVITY'];
  report.scope.officialElementaryItemTotal = 131;
  const validation = validateOfficialLearningItemCrosswalk(report);
  assert.ok(validation.errors.includes(`math_clause_maps_to_unknown_activity:${anyMathItem.officialCode}:UNKNOWN-ACTIVITY`));
  assert.ok(validation.errors.includes('national_coverage_must_remain_unknown_until_complete_enumeration'));

  const relationOnly = buildOfficialLearningItemCrosswalk().mathOfficialLearningContentItems.find((item) => item.coverageStatus === 'relation_only');
  assert.ok(relationOnly.activityIds.length > 0);
  assert.equal(relationOnly.activityEvidence.length, 0);
});
