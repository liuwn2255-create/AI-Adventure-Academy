import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { WEIGHT_MEASUREMENT_ADVENTURE as activity } from '../prototype/data/weightMeasurementAdventure.js';
import { CATALOG_CANDIDATE_TASK_BY_ID } from '../prototype/data/catalogCandidateTasks.js';
import { getGradeById } from '../prototype/data/gradeCatalog.js';
import { createLearningTaskSession, dispatchLearningTask, validateLearningTask } from '../prototype/learningTaskEngine.js';

const id = activity.activityId;
const send = (session, action, payload = {}) => dispatchLearningTask(session, activity, action, payload);

test('N-3-16 weight adventure is registered, traceable and candidate-only', () => {
  assert.deepEqual(validateLearningTask(activity), []);
  assert.equal(activity.status, 'candidate_pending_teacher_review');
  assert.equal(activity.teacherReview.status, 'not_reviewed');
  assert.equal(activity.evidencePolicy.persistence, 'memory_only_no_student_records_no_localStorage');
  assert.equal(activity.curriculumMapId, 'math-grade3-n-3-16-weight');
  assert.deepEqual(activity.curriculumCodes, ['N-3-16', 'n-II-9']);
  assert.equal(CATALOG_CANDIDATE_TASK_BY_ID.get(id), activity);
  const catalog = getGradeById('grade-3')?.subjects.find(({ subjectId }) => subjectId === 'mathematics')?.existingYearLevelContent.find((entry) => entry.activityId === id);
  assert.equal(catalog?.runtimeModule, activity.runtimeModule);
  const activityMap = JSON.parse(fs.readFileSync(new URL('../curriculum/learning-activity-map.json', import.meta.url), 'utf8'));
  assert.ok(activityMap.activities.some((entry) => entry.activityId === id && entry.runtimeReference.stageIds.length === activity.stages.length));
  const definition = JSON.parse(fs.readFileSync(new URL('../curriculum/learning-subitem-definitions.json', import.meta.url), 'utf8')).definitions.find(({ subitemId }) => subitemId === activity.coverage.subitemId);
  assert.equal(definition.officialCode, 'N-3-16');
  assert.equal(definition.officialPerformanceCode, 'n-II-9');
  assert.deepEqual(definition.evidenceStageIds, activity.stages.map(({ stageId }) => stageId));
  assert.ok(definition.notCovered.some((text) => text.includes('真實公斤秤')));
});

test('weight scale model validates bounds, equality and zero-difference edge cases', () => {
  let session = createLearningTaskSession(activity, 'weight-boundary');
  session = send(session, 'start').session;
  session = send(session, 'set_weight_estimate', { value: 700 }).session;
  assert.equal(send(session, 'set_weight_estimate', { value: 750 }).error, 'invalid_weight_estimate');
  let result = send(session, 'submit');
  assert.equal(result.attempt.result, 'incorrect');
  session = result.session;
  session = send(session, 'retry').session;
  session = send(session, 'set_weight_estimate', { value: 350 }).session;
  result = send(session, 'submit');
  assert.equal(result.attempt.result, 'correct');
  session = result.session;
  session = send(session, 'next').session;
  for (let index = 0; index < 6; index += 1) session = send(session, 'adjust_weight_pan', { side: 'right', delta: 1 }).session;
  assert.equal(send(session, 'adjust_weight_pan', { side: 'right', delta: 1 }).error, 'weight_counterweight_out_of_range');
  result = send(session, 'submit');
  assert.equal(result.attempt.result, 'incorrect');
  session = result.session;
  session = send(session, 'retry').session;
  for (let index = 0; index < 3; index += 1) session = send(session, 'adjust_weight_pan', { side: 'right', delta: 1 }).session;
  const balanced = send(session, 'submit');
  assert.equal(balanced.attempt.result, 'correct');
  assert.equal(balanced.attempt.response.leftGrams, balanced.attempt.response.rightGrams);
  session = send(balanced.session, 'next').session;
  session = send(session, 'set_weight_scale_reading', { value: 600 }).session;
  result = send(session, 'submit');
  assert.equal(result.attempt.result, 'correct');
  session = result.session;
  session = send(session, 'next').session;
  for (const item of activity.stages[3].weightRules.items) session = send(session, 'set_weight_scale_reading', { itemId: item.id, value: item.actualGrams }).session;
  session = send(session, 'set_weight_relation', { relation: '>' }).session;
  session = send(session, 'set_weight_difference', { value: 150 }).session;
  result = send(session, 'submit');
  assert.equal(result.attempt.result, 'correct');
  session = result.session;
  session = send(session, 'next').session;
  session = send(session, 'set_weight_scale_reading', { itemId: 'left', value: 250 }).session;
  session = send(session, 'set_weight_scale_reading', { itemId: 'right', value: 250 }).session;
  session = send(session, 'set_weight_relation', { relation: '=' }).session;
  session = send(session, 'set_weight_difference', { value: 0 }).session;
  const equal = send(session, 'submit');
  assert.equal(equal.attempt.result, 'correct');
  assert.equal(equal.attempt.response.difference, 0);
  session = send(session, 'next').session;
  assert.equal(send(session, 'set_weight_conversion', { kilograms: 10, grams: 0 }).error, 'invalid_weight_conversion');
});

test('all weight tasks support wrong feedback, hints, retry, new scenario, finish and replay', () => {
  let session = createLearningTaskSession(activity, 'weight-full-flow');
  session = send(session, 'start').session;
  let hint = send(session, 'hint');
  assert.equal(hint.hint, activity.stages[0].hints[0]);
  session = hint.session;
  hint = send(session, 'hint');
  assert.equal(hint.hint, activity.stages[0].hints[1]);
  session = hint.session;
  session = send(session, 'set_weight_estimate', { value: 100 }).session;
  let result = send(session, 'submit');
  assert.equal(result.attempt.result, 'incorrect');
  assert.match(result.session.lastFeedback.text, /估測/);
  session = send(result.session, 'retry').session;
  session = send(session, 'set_weight_estimate', { value: 350 }).session;
  result = send(session, 'submit');
  assert.equal(result.attempt.result, 'correct');
  session = result.session;
  session = send(session, 'next').session;

  session = send(session, 'adjust_weight_pan', { side: 'right', delta: 1 }).session;
  session = send(session, 'adjust_weight_pan', { side: 'right', delta: 1 }).session;
  result = send(session, 'submit');
  assert.equal(result.attempt.result, 'incorrect');
  assert.match(result.session.lastFeedback.text, /左盤還重/);
  session = send(result.session, 'retry').session;
  for (let index = 0; index < 3; index += 1) session = send(session, 'adjust_weight_pan', { side: 'right', delta: 1 }).session;
  result = send(session, 'submit');
  assert.equal(result.attempt.result, 'correct');
  session = send(result.session, 'next').session;

  session = send(session, 'set_weight_scale_reading', { value: 550 }).session;
  result = send(session, 'submit');
  assert.equal(result.attempt.result, 'incorrect');
  assert.match(result.session.lastFeedback.text, /刻度/);
  session = send(result.session, 'retry').session;
  session = send(session, 'set_weight_scale_reading', { value: 600 }).session;
  result = send(session, 'submit');
  assert.equal(result.attempt.result, 'correct');
  session = send(result.session, 'next').session;

  const firstCompare = activity.stages[3].weightRules;
  for (const item of firstCompare.items) session = send(session, 'set_weight_scale_reading', { itemId: item.id, value: item.actualGrams }).session;
  session = send(session, 'set_weight_relation', { relation: '>' }).session;
  session = send(session, 'set_weight_difference', { value: 100 }).session;
  result = send(session, 'submit');
  assert.equal(result.attempt.result, 'incorrect');
  assert.match(result.session.lastFeedback.text, /差值/);
  session = send(result.session, 'retry').session;
  for (const item of firstCompare.items) session = send(session, 'set_weight_scale_reading', { itemId: item.id, value: item.actualGrams }).session;
  session = send(session, 'set_weight_relation', { relation: '>' }).session;
  session = send(session, 'set_weight_difference', { value: 150 }).session;
  result = send(session, 'submit');
  assert.equal(result.attempt.result, 'correct');
  session = send(result.session, 'next').session;

  const equalRules = activity.stages[4].weightRules;
  for (const item of equalRules.items) session = send(session, 'set_weight_scale_reading', { itemId: item.id, value: item.actualGrams }).session;
  session = send(session, 'set_weight_relation', { relation: '=' }).session;
  session = send(session, 'set_weight_difference', { value: 0 }).session;
  result = send(session, 'submit');
  assert.equal(result.attempt.result, 'correct');
  session = send(result.session, 'next').session;

  session = send(session, 'set_weight_conversion', { kilograms: 1, grams: 200 }).session;
  result = send(session, 'submit');
  assert.equal(result.attempt.result, 'incorrect');
  assert.match(result.session.lastFeedback.text, /1,000/);
  session = send(result.session, 'retry').session;
  session = send(session, 'set_weight_conversion', { kilograms: 1, grams: 250 }).session;
  result = send(session, 'submit');
  assert.equal(result.attempt.result, 'correct');
  session = send(result.session, 'next').session;

  session = send(session, 'toggle_weight_supply_item', { itemId: 'water' }).session;
  result = send(session, 'submit');
  assert.equal(result.attempt.result, 'incorrect');
  assert.match(result.session.lastFeedback.text, /合計/);
  session = send(result.session, 'retry').session;
  session = send(session, 'toggle_weight_supply_item', { itemId: 'water' }).session;
  session = send(session, 'toggle_weight_supply_item', { itemId: 'map' }).session;
  result = send(session, 'submit');
  assert.equal(result.attempt.result, 'correct');
  session = send(result.session, 'next').session;
  assert.equal(session.phase, 'completed');
  const replay = send(session, 'restart', { sessionId: 'weight-replay' }).session;
  assert.equal(replay.phase, 'intro');
  assert.equal(replay.stageIndex, 0);
  assert.deepEqual(replay.attempts, []);
  assert.equal(activity.evidencePolicy.completionIsMastery, false);
});
